package io.quarkiverse.langchain4j.memorystore.infinispan.deployment;

import static io.quarkus.runtime.annotations.ConfigPhase.BUILD_TIME;

import java.util.Optional;

import io.quarkus.runtime.annotations.ConfigRoot;
import io.smallrye.config.ConfigMapping;
import io.smallrye.config.WithDefault;

@ConfigRoot(phase = BUILD_TIME)
@ConfigMapping(prefix = "quarkus.langchain4j.memorystore.infinispan")
public interface InfinispanMemoryStoreBuildTimeConfig {

    /**
     * The name of the Infinispan client to use. These clients are configured by means of the {@code infinispan-client}
     * extension.
     * If unspecified, it will use the default Infinispan client.
     */
    Optional<String> clientName();

    /**
     * The name of the Infinispan cache to use for storing chat memory.
     * If unspecified, it will use {@code chat-memory}.
     */
    Optional<String> cacheName();

    /**
     * Whether to create the cache on startup if it does not exist.
     * Set to {@code false} if the cache is pre-configured on the Infinispan server.
     */
    @WithDefault("true")
    boolean createCache();

    /**
     * Optional full XML or JSON cache configuration.
     * When provided, this overrides the default cache configuration generated by the extension.
     */
    Optional<String> cacheConfig();
}
